/** "android.permission.CAMERA" → { vi: "Máy ảnh", raw: "CAMERA" }; unknown permissions keep only the raw name. */
export function permName(full: string): { vi?: string; raw: string } {
  const raw = full.replace(/^android\.permission\.|^com\.google\.android\.[\w.]*permission\./, '')
  return { vi: PERM_VI[raw], raw }
}
